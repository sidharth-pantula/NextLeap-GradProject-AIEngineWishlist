def test_api_wishlist_endpoints(client):
    """Verify all FastAPI REST endpoints for the Wishlist Decision Journey."""
    # 1. Intent endpoint
    res = client.get("/api/wishlist/intent")
    assert res.status_code == 200
    assert "strict_purchase_intent_pct" in res.json()

    # 2. Save reasons endpoint
    res = client.get("/api/wishlist/save-reasons")
    assert res.status_code == 200
    assert isinstance(res.json(), list)

    # 3. States endpoint
    res = client.get("/api/wishlist/states")
    assert res.status_code == 200
    assert len(res.json()) == 12

    # 4. Triggers endpoint
    res = client.get("/api/wishlist/triggers")
    assert res.status_code == 200
    assert "observed_stated" in res.json()

    # 5. Gaps endpoint
    res = client.get("/api/wishlist/information-gaps")
    assert res.status_code == 200
    assert "information_gaps" in res.json()

    # 6. Confidence behaviours endpoint
    res = client.get("/api/wishlist/confidence-behaviours")
    assert res.status_code == 200
    assert isinstance(res.json(), list)
    assert len(res.json()) >= 5


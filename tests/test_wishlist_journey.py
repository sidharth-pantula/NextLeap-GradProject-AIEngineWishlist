def test_intent_metrics_strict_vs_broader(journey_engine):
    """Verify Strict Purchase Intent and Broader Commercial Intent mathematical consistency."""
    metrics = journey_engine.get_intent_metrics()
    
    assert "total_analyzed" in metrics
    assert "strict_purchase_intent_pct" in metrics
    assert "broader_commercial_intent_pct" in metrics
    assert "sanity_check_flagged" in metrics
    
    # Broader commercial intent must be >= Strict purchase intent
    assert metrics["broader_commercial_intent_pct"] >= metrics["strict_purchase_intent_pct"]
    assert metrics["total_analyzed"] > 0
    assert len(metrics["tiers"]) == 7


